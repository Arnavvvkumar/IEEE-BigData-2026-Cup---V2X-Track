"""Scratch (random-init) batch-1 PV-RCNN config for the Track B three-class custom data.

Shares Codex's DATA_CONFIG (voxelnext_v1.yaml / second_control_v1.yaml: classes, range [-40,-40,-8,40,40,2], flips,
rotation, scaling, CustomDataset infos) so PV-RCNN is directly comparable with the SECOND control/mix pair. Model = OpenPCDet's
stock custom_models/pv_rcnn.yaml (commit 233f8498) with only Track-B adaptations:
  * voxel 0.05 x 0.05 x 0.25 m -> grid 1600 x 1600 x 40 (KITTI-like 0.4 m BEV cells after stride 8; z 40 like KITTI's 41-slice input)
  * MAX_NUMBER_OF_VOXELS sized from a full-dataset occupancy audit (pvrcnn_preflight.py) instead of the KITTI 16k/40k
  * anchors: per-class median size and median bottom height of the frozen Generator V2 train boxes (Codex's SECOND rule)
  * 360-degree 80 x 80 m scenes: 4096 keypoints (PV-RCNN Waymo setting) instead of 2048 (KITTI front view)
  * batch 1, 12 epochs (matches the SECOND pair), adam_onecycle LR 0.002, score threshold 0.05 (matches SECOND)
No pretrained weights are referenced anywhere.
"""
import argparse
import copy
import hashlib
import pickle
from pathlib import Path

import numpy as np
import yaml


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--repo', type=Path, required=True)
    ap.add_argument('--shared', type=Path, required=True, help='Codex shared data config, e.g. second_control_v1.yaml')
    ap.add_argument('--base', type=Path, required=True, help='frozen Generator V2 OpenPCDet dataset (anchor statistics)')
    ap.add_argument('--data-path', required=True)
    ap.add_argument('--max-voxels', type=int, required=True)
    ap.add_argument('--out', type=Path, required=True)
    a = ap.parse_args(argv)
    stock = yaml.safe_load((a.repo / 'tools/cfgs/custom_models/pv_rcnn.yaml').read_text())
    shared = yaml.safe_load(a.shared.read_text())
    cfg = copy.deepcopy(stock)
    cfg['CLASS_NAMES'] = list(shared['CLASS_NAMES'])
    cfg['DATA_CONFIG'] = copy.deepcopy(shared['DATA_CONFIG'])
    cfg['DATA_CONFIG']['DATA_PATH'] = a.data_path
    vox = cfg['DATA_CONFIG']['DATA_PROCESSOR'][-1]
    assert vox['NAME'] == 'transform_points_to_voxels'
    vox['VOXEL_SIZE'] = [0.05, 0.05, 0.25]
    vox['MAX_POINTS_PER_VOXEL'] = 5
    vox['MAX_NUMBER_OF_VOXELS'] = {'train': a.max_voxels, 'test': a.max_voxels}
    train = pickle.loads((a.base / 'custom_infos_train.pkl').read_bytes())
    anchors = cfg['MODEL']['DENSE_HEAD']['ANCHOR_GENERATOR_CONFIG']
    template = {'vehicle': anchors[0], 'pedestrian': anchors[1], 'truck': anchors[0]}
    new = []
    for c in cfg['CLASS_NAMES']:
        boxes = np.concatenate([r['annos']['gt_boxes_lidar'][r['annos']['name'] == c] for r in train if len(r['annos']['name'])])
        an = copy.deepcopy(template[c])
        an.update(class_name=c, anchor_sizes=[np.median(boxes[:, 3:6], axis=0).round(4).tolist()],
                  anchor_bottom_heights=[round(float(np.median(boxes[:, 2] - boxes[:, 5] / 2)), 4)])
        if c == 'truck':
            an.update(matched_threshold=0.5, unmatched_threshold=0.35)
        new.append(an)
    cfg['MODEL']['DENSE_HEAD']['ANCHOR_GENERATOR_CONFIG'] = new
    cfg['MODEL']['PFE']['NUM_KEYPOINTS'] = 4096
    cfg['MODEL']['POST_PROCESSING']['SCORE_THRESH'] = 0.05
    opt = cfg['OPTIMIZATION']
    opt.update(BATCH_SIZE_PER_GPU=1, NUM_EPOCHS=12, LR=0.002)
    src = {'stock_pv_rcnn_sha256': hashlib.sha256((a.repo / 'tools/cfgs/custom_models/pv_rcnn.yaml').read_bytes()).hexdigest(),
           'shared_data_config_sha256': hashlib.sha256(a.shared.read_bytes()).hexdigest()}
    with a.out.open('x') as f:
        f.write('# Generated by experiments/claude_carla_overnight/pvrcnn/make_pvrcnn_config.py; scratch init, batch 1.\n')
        f.write(f"# stock pv_rcnn.yaml sha256 {src['stock_pv_rcnn_sha256']}; shared DATA_CONFIG from sha256 {src['shared_data_config_sha256']}\n")
        yaml.safe_dump(cfg, f, sort_keys=False)
    print(a.out)


if __name__ == '__main__':
    main()
