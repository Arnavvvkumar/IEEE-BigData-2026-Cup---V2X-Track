"""second_relabel_v1.yaml = Codex's second_control_v1.yaml with ONLY DATA_PATH and the anchors changed.
Anchors follow Codex's rule (per-class median size and median bottom height of the training boxes), recomputed on the
relabelled training set so the anchor sizes match the new label convention. Everything else (voxels, seed, epochs,
optimizer, thresholds) is identical to the matched SECOND control/mix runs."""
import pickle
import sys
from pathlib import Path

import numpy as np
import yaml

W = Path(__file__).resolve().parents[3]
src = W / 'experiments/detector_program/second_control_v1.yaml'
data = Path.home() / 'projects/bdc2026-track-b/data/claude_v2carla_relabel_mix6000_v1'
cfg = yaml.safe_load(src.read_text())
cfg['DATA_CONFIG']['DATA_PATH'] = str(data)
train = pickle.loads((data / 'custom_infos_train.pkl').read_bytes())
for an in cfg['MODEL']['DENSE_HEAD']['ANCHOR_GENERATOR_CONFIG']:
    c = an['class_name']
    b = np.concatenate([r['annos']['gt_boxes_lidar'][r['annos']['name'] == c] for r in train if len(r['annos']['name'])])
    an['anchor_sizes'] = [np.median(b[:, 3:6], axis=0).astype(float).round(4).tolist()]
    an['anchor_bottom_heights'] = [round(float(np.median(b[:, 2] - b[:, 5] / 2)), 4)]
    print(c, an['anchor_sizes'], an['anchor_bottom_heights'])
out = Path(__file__).with_name('second_relabel_v1.yaml')
with out.open('x') as f:
    f.write('# Generated by boxsize/make_second_relabel_config.py from second_control_v1.yaml; only DATA_PATH and anchors differ.\n')
    yaml.safe_dump(cfg, f, sort_keys=False)
print(out)
