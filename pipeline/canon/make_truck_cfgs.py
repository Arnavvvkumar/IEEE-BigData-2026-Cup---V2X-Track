"""Truck-only configs for the OSC specialists (T1 PV-RCNN, T2 SECOND): same as the 3-class configs, but CLASS_NAMES = [truck], so vehicle
and pedestrian boxes are background; three truck anchor sizes (bank truck / pickup-van / long-low) instead of one.
writes canon/pvrcnn_truck.yaml and canon/second_truck.yaml"""
from pathlib import Path

import yaml

H = Path(__file__).parent
SIZES = [[8.468, 2.9039, 3.6147], [5.8, 2.25, 2.2], [8.5, 2.8, 2.5]]
for src, dst in (('pvrcnn_all.yaml', 'pvrcnn_truck.yaml'), ('second_canon_all_v1.yaml', 'second_truck.yaml')):
    c = yaml.safe_load((H / src).read_text())
    c['CLASS_NAMES'] = ['truck']
    c['DATA_CONFIG']['MAP_CLASS_TO_KITTI'] = {'truck': 'Car'}
    anchors = [a for a in c['MODEL']['DENSE_HEAD']['ANCHOR_GENERATOR_CONFIG'] if a['class_name'] == 'truck']
    assert len(anchors) == 1
    anchors[0]['anchor_sizes'] = SIZES
    c['MODEL']['DENSE_HEAD']['ANCHOR_GENERATOR_CONFIG'] = anchors
    (H / dst).write_text('# Truck-only specialist, generated by make_truck_cfgs.py from ' + src + '\n' + yaml.safe_dump(c, sort_keys=False))
    print(dst, 'classes', c['CLASS_NAMES'], 'anchors', anchors[0]['anchor_sizes'], 'batch', c['OPTIMIZATION']['BATCH_SIZE_PER_GPU'], 'epochs', c['OPTIMIZATION']['NUM_EPOCHS'])

# P1: pedestrian-only PV-RCNN specialist (same model, pedestrian class only; one pedestrian anchor as in the 3-class config)
c = yaml.safe_load((H / 'pvrcnn_all.yaml').read_text())
c['CLASS_NAMES'] = ['pedestrian']
c['DATA_CONFIG']['MAP_CLASS_TO_KITTI'] = {'pedestrian': 'Pedestrian'}
c['MODEL']['DENSE_HEAD']['ANCHOR_GENERATOR_CONFIG'] = [a for a in c['MODEL']['DENSE_HEAD']['ANCHOR_GENERATOR_CONFIG'] if a['class_name'] == 'pedestrian']
(H / 'pvrcnn_ped.yaml').write_text('# Pedestrian-only specialist, generated by make_truck_cfgs.py from pvrcnn_all.yaml\n' + yaml.safe_dump(c, sort_keys=False))
print('pvrcnn_ped.yaml classes', c['CLASS_NAMES'], 'anchors', c['MODEL']['DENSE_HEAD']['ANCHOR_GENERATOR_CONFIG'][0]['anchor_sizes'])

