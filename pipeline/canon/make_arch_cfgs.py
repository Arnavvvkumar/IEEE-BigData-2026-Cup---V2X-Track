"""Pedestrian-only specialists with NEW architectures (ensemble diversity): Part-A2 and Voxel R-CNN.
DATA_CONFIG, CLASS_NAMES, OPTIMIZATION and the pedestrian anchor come from pvrcnn_ped.yaml (same synthetic data recipe as P1-P3);
MODEL comes from OpenPCDet's kitti_models config. Writes parta2_ped.yaml and voxelrcnn_ped.yaml next to this file.
usage: make_arch_cfgs.py <OpenPCDet repo>"""
import copy
import sys
from pathlib import Path

import yaml

here = Path(__file__).parent
repo = Path(sys.argv[1])
ped = yaml.safe_load((here / 'pvrcnn_ped.yaml').read_text())
anchor = ped['MODEL']['DENSE_HEAD']['ANCHOR_GENERATOR_CONFIG']
for src, dst in (('PartA2.yaml', 'parta2_ped.yaml'), ('voxel_rcnn_car.yaml', 'voxelrcnn_ped.yaml')):
    k = yaml.safe_load((repo / 'tools/cfgs/kitti_models' / src).read_text())
    m = copy.deepcopy(k['MODEL'])
    m['DENSE_HEAD']['ANCHOR_GENERATOR_CONFIG'] = copy.deepcopy(anchor)
    # Pedestrian anchor matching thresholds (KITTI pedestrian values), like the PV-RCNN specialist
    for a in m['DENSE_HEAD']['ANCHOR_GENERATOR_CONFIG']:
        a.setdefault('matched_threshold', 0.5); a.setdefault('unmatched_threshold', 0.35)
    m['POST_PROCESSING'] = copy.deepcopy(ped['MODEL']['POST_PROCESSING'])
    cfg = {'CLASS_NAMES': ['pedestrian'], 'DATA_CONFIG': copy.deepcopy(ped['DATA_CONFIG']), 'MODEL': m,
           'OPTIMIZATION': copy.deepcopy(ped['OPTIMIZATION'])}
    (here / dst).write_text(f'# Pedestrian-only {m["NAME"]} specialist, generated by make_arch_cfgs.py (data/opt from pvrcnn_ped.yaml)\n'
                            + yaml.safe_dump(cfg, sort_keys=False))
    print('wrote', dst, m['NAME'], [a['class_name'] for a in m['DENSE_HEAD']['ANCHOR_GENERATOR_CONFIG']])
