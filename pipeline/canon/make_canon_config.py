"""SECOND config for a ground-canonical dataset: second_relabel_v1.yaml with DATA_PATH, anchors (training medians), a small
z-jitter augmentation (covers ground-fit error) and voxel caps raised so frames are not truncated.
usage: make_canon_config.py <dataset> <out.yaml> [z_jitter_std]"""
import pickle
import sys
from pathlib import Path

import numpy as np
import yaml

W = Path(__file__).resolve().parents[3]
data, out = Path(sys.argv[1]), Path(sys.argv[2])
zj = float(sys.argv[3]) if len(sys.argv) > 3 else 0.15
cfg = yaml.safe_load((W / 'experiments/claude_carla_overnight/boxsize/second_relabel_v1.yaml').read_text())
cfg['DATA_CONFIG']['DATA_PATH'] = str(data)
train = pickle.loads((data / 'custom_infos_train.pkl').read_bytes())
for an in cfg['MODEL']['DENSE_HEAD']['ANCHOR_GENERATOR_CONFIG']:
    c = an['class_name']
    b = np.concatenate([r['annos']['gt_boxes_lidar'][r['annos']['name'] == c] for r in train if len(r['annos']['name'])])
    an['anchor_sizes'] = [np.median(b[:, 3:6], axis=0).astype(float).round(4).tolist()]
    an['anchor_bottom_heights'] = [round(float(np.median(b[:, 2] - b[:, 5] / 2)), 4)]
    print(c, an['anchor_sizes'], an['anchor_bottom_heights'], 'bottom p1/p99', np.percentile(b[:, 2] - b[:, 5] / 2, [1, 99]).round(2))
cfg['DATA_CONFIG']['DATA_AUGMENTOR']['AUG_CONFIG_LIST'].append({'NAME': 'random_world_translation', 'NOISE_TRANSLATE_STD': [0.0, 0.0, zj]})
vox = cfg['DATA_CONFIG']['DATA_PROCESSOR'][-1]
vox['MAX_NUMBER_OF_VOXELS'] = {'train': 40000, 'test': 60000}
with out.open('x') as f:
    f.write('# Generated by canon/make_canon_config.py from boxsize/second_relabel_v1.yaml: DATA_PATH, anchors, z jitter, voxel caps.\n')
    yaml.safe_dump(cfg, f, sort_keys=False)
print(out)
