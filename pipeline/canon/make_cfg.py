"""Derive a config for a ground-canonical dataset from any existing OpenPCDet yaml.
usage: make_cfg.py <src.yaml> <dataset> <out.yaml> [key=value ...]
keys: zjitter=0.15  train_voxels=40000  test_voxels=60000  score=0.05  keypoints=N  intensity=1 (adds zero intensity feature)
Anchors (if the head has them) are recomputed as per-class training medians. Nothing else changes."""
import pickle
import sys
from pathlib import Path

import numpy as np
import yaml

src, data, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
opt = dict(kv.split('=') for kv in sys.argv[4:])
cfg = yaml.safe_load(src.read_text())
cfg['DATA_CONFIG']['DATA_PATH'] = str(data)
train = pickle.loads((data / 'custom_infos_train.pkl').read_bytes())
for an in cfg['MODEL']['DENSE_HEAD'].get('ANCHOR_GENERATOR_CONFIG', []):
    c = an['class_name']
    b = np.concatenate([r['annos']['gt_boxes_lidar'][r['annos']['name'] == c] for r in train if len(r['annos']['name'])])
    an['anchor_sizes'] = [np.median(b[:, 3:6], axis=0).astype(float).round(4).tolist()]
    an['anchor_bottom_heights'] = [round(float(np.median(b[:, 2] - b[:, 5] / 2)), 4)]
aug = cfg['DATA_CONFIG']['DATA_AUGMENTOR']['AUG_CONFIG_LIST']
aug[:] = [x for x in aug if x['NAME'] != 'random_world_translation']
aug.append({'NAME': 'random_world_translation', 'NOISE_TRANSLATE_STD': [0.0, 0.0, float(opt.get('zjitter', 0.15))]})
vox = cfg['DATA_CONFIG']['DATA_PROCESSOR'][-1]
vox['MAX_NUMBER_OF_VOXELS'] = {'train': int(opt.get('train_voxels', 40000)), 'test': int(opt.get('test_voxels', 60000))}
if opt.get('intensity') == '1' and 'intensity' not in cfg['DATA_CONFIG']['POINT_FEATURE_ENCODING']['used_feature_list']:
    cfg['DATA_CONFIG']['POINT_FEATURE_ENCODING']['used_feature_list'].append('intensity')
if 'score' in opt:
    pp = cfg['MODEL']['DENSE_HEAD'].get('POST_PROCESSING') or cfg['MODEL']['POST_PROCESSING']
    pp['SCORE_THRESH'] = float(opt['score'])
with out.open('x') as f:
    f.write(f'# Generated by canon/make_cfg.py from {src.name} with {opt}; anchors = training medians of {data.name}.\n')
    yaml.safe_dump(cfg, f, sort_keys=False)
print(out)
